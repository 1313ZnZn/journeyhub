/* Regenerates desktop-theme-map.css: light equivalents of colors hard-coded for the dark mobile theme.
   Run after changing any page CSS: node work/journeyhub/make-desktop-theme.cjs */
const fs=require('fs'),path=require('path');
const root=__dirname;
const build=fs.readFileSync(path.join(root,'build.cjs'),'utf8');
const files=build.match(/'[a-z0-9-]+\.css'/g).map(x=>x.slice(1,-1)).filter(x=>!x.startsWith('desktop-'));
const html=fs.readFileSync(path.join(root,'original.html'),'utf8');
const sources=[html.match(/<style[^>]*>([\s\S]*?)<\/style>/)[1],...[...new Set(files)].map(f=>fs.readFileSync(path.join(root,f),'utf8'))];

// Text sits on photography or stays intentionally dark in these components.
const KEEP=/hero|cover|poster|\.deep|photo|overlay|scrim|lightbox|toast|\.pin\b|mlabel|map-top|ix-card-image|jm-map|jm-world|gm-|leaflet|amap|tile-ic|\.qr|ticket-stub/;

function rgbToHsl(r,g,b){r/=255;g/=255;b/=255;const M=Math.max(r,g,b),m=Math.min(r,g,b),l=(M+m)/2;if(M===m)return [0,0,l];const d=M-m,s=l>.5?d/(2-M-m):d/(M+m);const h=M===r?(g-b)/d+(g<b?6:0):M===g?(b-r)/d+2:(r-g)/d+4;return [h*60,s,l];}
function parseHex(x){let h=x.slice(1);if(h.length<=4)h=[...h].map(c=>c+c).join('');return [parseInt(h.slice(0,2),16),parseInt(h.slice(2,4),16),parseInt(h.slice(4,6),16),h.length===8?parseInt(h.slice(6,8),16)/255:1];}
const COLOR=/#[0-9a-f]{3,8}\b|rgba?\([^)]*\)/gi;
function parseColor(c){if(c[0]==='#')return parseHex(c);const n=c.match(/[\d.]+%?/g).map(v=>v.endsWith('%')?parseFloat(v)/100:parseFloat(v));return [n[0],n[1],n[2],n[3]===undefined?1:n[3]];}
const hsla=(h,s,l,a)=>`hsl(${Math.round(h)} ${Math.round(s*100)}% ${Math.round(l*100)}%${a<1?` / ${+a.toFixed(2)}`:''})`;
const toSurface=c=>{const [r,g,b,a]=parseColor(c),[h,s,l]=rgbToHsl(r,g,b);if(l>=.36)return c;return s<.12?hsla(h,.08,.965,a):hsla(h,Math.min(s,.7),.93,a);};
const toText=(c,keepWhite)=>{const [r,g,b,a]=parseColor(c),[h,s,l]=rgbToHsl(r,g,b);if(l<.55)return c;if(l>.97&&keepWhite)return c;return s<.12?hsla(h,.04,.3,a):hsla(h,Math.min(s,.75),.26,a);};
const toBorder=c=>{const [r,g,b]=parseColor(c),[,,l]=rgbToHsl(r,g,b);return l<.36?'var(--line)':c;};

function convert(selector,decls){
  const out=[];let surfaced=false;
  for(const [p,v] of decls)if(/^background/.test(p)&&v.match(COLOR)&&v.replace(COLOR,c=>toSurface(c))!==v)surfaced=true;
  for(const [p,v] of decls){
    if(!v.match(COLOR)||/url\(/.test(v))continue;
    let next=v;
    if(/^background/.test(p))next=v.replace(COLOR,toSurface);
    else if(p==='color'||p==='fill'||p==='stroke'||p==='caret-color')next=v.replace(COLOR,c=>toText(c,!surfaced));
    else if(/^(border|outline)/.test(p))next=v.replace(COLOR,toBorder);
    else if(p==='box-shadow'){if(!/inset/.test(v))next='var(--dk-card-shadow)';}
    else if(p.startsWith('--')){const [r,g,b]=parseColor(v.match(COLOR)[0]),l=rgbToHsl(r,g,b)[2];next=l<.36?v.replace(COLOR,toSurface):v.replace(COLOR,c=>toText(c,false));}
    if(next!==v)out.push(`${p}:${next}`);
  }
  return out;
}
function prefix(sel){
  return sel.split(/,(?![^(]*\))/).map(s=>s.trim().replace(/^:root:not\(\[data-theme=["']?light["']?\]\)\s*/,'').replace(/^:root\[data-theme=["']?dark["']?\]\s*/,'')).filter(s=>s&&!/^(:root|html|body|\.stage|\.device|#app|\*|@)/.test(s)&&!KEEP.test(s)).map(s=>'#app '+s).join(',');
}
const rules=[];
function walk(css){
  css=css.replace(/\/\*[\s\S]*?\*\//g,'');
  let i=0;
  while(i<css.length){
    const open=css.indexOf('{',i);if(open<0)break;
    const head=css.slice(i,open).trim();
    let depth=1,j=open+1;while(j<css.length&&depth){if(css[j]==='{')depth++;else if(css[j]==='}')depth--;j++;}
    const body=css.slice(open+1,j-1);
    if(head.startsWith('@media')){if(/prefers-color-scheme:\s*dark/.test(head))walk(body);}
    else if(!head.startsWith('@')){
      const decls=body.split(/;(?![^(]*\))/).map(d=>{const k=d.indexOf(':');return k<0?null:[d.slice(0,k).trim().toLowerCase(),d.slice(k+1).replace(/!important/,'').trim()];}).filter(Boolean);
      const sel=prefix(head);
      if(sel){const c=convert(head,decls);if(c.length)rules.push(`${sel}{${c.join(';')}}`);}
    }
    i=j;
  }
}
sources.forEach(walk);
const output=`/* Generated by make-desktop-theme.cjs. Do not edit by hand. */\n@media(min-width:1024px){\n${rules.join('\n')}\n}\n`;
fs.writeFileSync(path.join(root,'desktop-theme-map.css'),output);
console.log(JSON.stringify({rules:rules.length,bytes:Buffer.byteLength(output)}));
