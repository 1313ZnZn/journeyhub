BEGIN;
CREATE FUNCTION pg_temp.assert_true(ok boolean, label text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN IF ok IS DISTINCT FROM true THEN RAISE EXCEPTION 'TEST FAILED: %',label; END IF; END $$;
DO $$
DECLARE a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid();
  ta uuid; tb uuid; r jsonb; r2 jsonb; id text; rid uuid; snapshot jsonb; failed boolean; oldstock int;
BEGIN
  INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES(a,'jh-sql-a@example.invalid','{"display_name":"Test A"}'),(b,'jh-sql-b@example.invalid','{"display_name":"Test B"}'),(c,'jh-sql-c@example.invalid','{"display_name":"Test C"}'),(d,'jh-sql-d@example.invalid','{"display_name":"Test D"}');
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',a)::text,true);
  PERFORM journey_hub.command('profile','{}',gen_random_uuid());
  SELECT traveler_id INTO ta FROM journey_hub.travelers WHERE auth_user_id=a;
  PERFORM pg_temp.assert_true(ta IS NOT NULL,'profile creation');
  SELECT stock INTO oldstock FROM journey_hub.inventory WHERE product_id='tote';
  rid:=gen_random_uuid();
  r:=journey_hub.command('order','{"items":[{"pid":"tote","qty":1,"price":1}],"method":"hotel","address":{"guest":"Test A","room":"101"},"total":1}',rid);
  r2:=journey_hub.command('order','{"items":[{"pid":"tote","qty":1,"price":1}],"method":"hotel","address":{"guest":"Test A","room":"101"},"total":1}',rid);
  id:=r->>'id';
  PERFORM pg_temp.assert_true(r=r2,'idempotent order');
  PERFORM pg_temp.assert_true((SELECT total_thb=720 FROM journey_hub.orders WHERE order_id=id),'server-side price');
  PERFORM pg_temp.assert_true((SELECT stock=oldstock-1 FROM journey_hub.inventory WHERE product_id='tote'),'one stock reservation');
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',b)::text,true);
  PERFORM journey_hub.command('profile','{}',gen_random_uuid());
  snapshot:=journey_hub.snapshot();
  PERFORM pg_temp.assert_true(jsonb_array_length(snapshot->'orders')=0,'other user cannot read orders');
  failed:=false; BEGIN PERFORM journey_hub.command('cancelOrder',jsonb_build_object('id',id),gen_random_uuid()); EXCEPTION WHEN insufficient_privilege THEN failed:=true; END;
  PERFORM pg_temp.assert_true(failed,'other user cannot cancel');
  failed:=false; BEGIN PERFORM journey_hub.command('checkin','{"id":"B-4102","checked":true}',gen_random_uuid()); EXCEPTION WHEN insufficient_privilege THEN failed:=true; END;
  PERFORM pg_temp.assert_true(failed,'traveler cannot check in');
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',a)::text,true);
  PERFORM journey_hub.command('cancelOrder',jsonb_build_object('id',id),gen_random_uuid());
  PERFORM pg_temp.assert_true((SELECT stock=oldstock FROM journey_hub.inventory WHERE product_id='tote'),'stock returned');
  failed:=false; BEGIN PERFORM journey_hub.command('cancelOrder',jsonb_build_object('id',id),gen_random_uuid()); EXCEPTION WHEN raise_exception THEN failed:=true; END;
  PERFORM pg_temp.assert_true(failed,'cannot return stock twice');
  UPDATE journey_hub.sessions SET capacity=1,seats_held_other_channels=0 WHERE session_id='c20';
  r:=journey_hub.command('book','{"sessionId":"c20","guests":1}',gen_random_uuid());
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',b)::text,true);
  failed:=false; BEGIN PERFORM journey_hub.command('book','{"sessionId":"c20","guests":1}',gen_random_uuid()); EXCEPTION WHEN raise_exception THEN failed:=true; END;
  PERFORM pg_temp.assert_true(failed,'cannot oversell capacity');
  UPDATE journey_hub.staff SET auth_user_id=c WHERE staff_id='PS-1024';
  UPDATE journey_hub.staff SET auth_user_id=d WHERE staff_id='NT-2001';
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',c)::text,true);
  PERFORM journey_hub.command('plan','{"id":"sat-24-oct","action":"save","time":"am","cap":25,"price":1500,"promo":1000,"reason":"Integration test draft"}',gen_random_uuid());
  PERFORM journey_hub.command('plan','{"id":"sat-24-oct","action":"submit"}',gen_random_uuid());
  failed:=false; BEGIN PERFORM journey_hub.command('plan','{"id":"sat-24-oct","action":"approve"}',gen_random_uuid()); EXCEPTION WHEN insufficient_privilege THEN failed:=true; END;
  PERFORM pg_temp.assert_true(failed,'coordinator cannot approve');
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',d)::text,true);
  PERFORM journey_hub.command('plan','{"id":"sat-24-oct","action":"approve"}',gen_random_uuid());
  PERFORM pg_temp.assert_true((SELECT status='approved' AND created_session_id IS NOT NULL FROM journey_hub.session_plans WHERE plan_id='sat-24-oct'),'manager creates session atomically');
  PERFORM set_config('request.jwt.claims','{}',true);
  snapshot:=journey_hub.snapshot();
  PERFORM pg_temp.assert_true(jsonb_array_length(snapshot->'bookings')=0 AND jsonb_array_length(snapshot->'orders')=0 AND snapshot->'staff'='null'::jsonb,'guest privacy');
  failed:=false; BEGIN PERFORM journey_hub.command('profile','{}',gen_random_uuid()); EXCEPTION WHEN insufficient_privilege THEN failed:=true; END;
  PERFORM pg_temp.assert_true(failed,'anonymous writes denied');
END $$;
SET LOCAL ROLE anon;
SELECT pg_temp.assert_true(jsonb_array_length(public.journeyhub_snapshot()->'products')=4,'anonymous catalog API');
RESET ROLE;
SELECT 'PASS: profile, price integrity, idempotency, stock reserve/return, ownership, check-in permissions, capacity, approval transaction, guest privacy' AS result;
ROLLBACK;
